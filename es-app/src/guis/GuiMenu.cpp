void GuiMenu::openQuitMenu()
{
	auto s = new GuiSettings(mWindow, "QUIT");

	Window* window = mWindow;

	// command line switch
	bool confirm_quit = Settings::getInstance()->getBool("ConfirmQuit");

	ComponentListRow row;
	if (UIModeController::getInstance()->isUIModeFull())
	{
		auto static restart_es_fx = []() {
			Scripting::fireEvent("quit");
			if (quitES(QuitMode::RESTART)) {
				LOG(LogWarning) << "Restart terminated with non-zero result!";
			}
		};

		if (confirm_quit) {
			row.makeAcceptInputHandler([window] {
				window->pushGui(new GuiMsgBox(window, "REALLY RESTART?", "YES", restart_es_fx, "NO", nullptr));
			});
		} else {
			row.makeAcceptInputHandler(restart_es_fx);
		}
		row.addElement(std::make_shared<TextComponent>(window, "RESTART EMULATIONSTATION", Font::get(FONT_SIZE_MEDIUM), 0xBCBEBCFF), true);
		s->addRow(row);

		if(Settings::getInstance()->getBool("ShowExit"))
		{
			auto static quit_es_fx = [] {
				Scripting::fireEvent("quit");
				quitES();
			};

			row.elements.clear();
			if (confirm_quit) {
				row.makeAcceptInputHandler([window] {
					window->pushGui(new GuiMsgBox(window, "REALLY QUIT?", "YES", quit_es_fx, "NO", nullptr));
				});
			} else {
				row.makeAcceptInputHandler(quit_es_fx);
			}
			row.addElement(std::make_shared<TextComponent>(window, "QUIT EMULATIONSTATION", Font::get(FONT_SIZE_MEDIUM), 0xBCBEBCFF), true);
			s->addRow(row);
		}
	}

	auto static reboot_sys_fx = [] {
		Scripting::fireEvent("quit", "reboot");
		Scripting::fireEvent("reboot");
		if (quitES(QuitMode::REBOOT)) {
			LOG(LogWarning) << "Restart terminated with non-zero result!";
		}
	};

	row.elements.clear();
	if (confirm_quit) {
		row.makeAcceptInputHandler([window] {
			window->pushGui(new GuiMsgBox(window, "REALLY RESTART?", "YES", {reboot_sys_fx}, "NO", nullptr));
		});
	} else {
		row.makeAcceptInputHandler(reboot_sys_fx);
	}
	row.addElement(std::make_shared<TextComponent>(window, "RESTART SYSTEM", Font::get(FONT_SIZE_MEDIUM), 0xBCBEBCFF), true);
	s->addRow(row);

	auto static shutdown_sys_fx = [] {
		Scripting::fireEvent("quit", "shutdown");
		Scripting::fireEvent("shutdown");
		if (quitES(QuitMode::SHUTDOWN)) {
			LOG(LogWarning) << "Shutdown terminated with non-zero result!";
		}
	};

	row.elements.clear();
	if (confirm_quit) {
		row.makeAcceptInputHandler([window] {
			window->pushGui(new GuiMsgBox(window, "REALLY SHUTDOWN?", "YES", shutdown_sys_fx, "NO", nullptr));
		});
	} else {
		row.makeAcceptInputHandler(shutdown_sys_fx);
	}
	row.addElement(std::make_shared<TextComponent>(window, "SHUTDOWN SYSTEM", Font::get(FONT_SIZE_MEDIUM), 0xBCBEBCFF), true);
	s->addRow(row);
	mWindow->pushGui(s);
}

// BTV9: procura versão nova nos releases do GitHub (/opt/btv9/es-update.sh menu) e,
// se houver, oferece reiniciar o ES para instalar (a instalação roda antes de o ES iniciar)
#define UPDATE_SCRIPT "/opt/btv9/es-update.sh"
void GuiMenu::checkUpdate(Window* window)
{
	window->pushGui(new GuiBusy(window, "PROCURANDO ATUALIZAÇÃO",
		[] { return btv9RunRoot(UPDATE_SCRIPT, { "menu" }); },
		[window](const std::string& out) {
			// saída: "<ESTADO> <versão>"; ESTADO = PRONTA (baixada), ATUAL ou ERRO
			std::string state = out.substr(0, out.find(' '));
			std::string ver = out.find(' ') == std::string::npos ? "" : out.substr(out.find(' ') + 1);
			ver = Utils::String::toUpper(ver.substr(0, ver.find('\n')));
			if(state == "PRONTA")
				window->pushGui(new GuiMsgBox(window, "VERSÃO NOVA BAIXADA: " + ver + "\nREINICIAR O EMULATIONSTATION AGORA PARA INSTALAR?",
					"SIM", [] { btv9RunRoot(UPDATE_SCRIPT, { "restart" }); },
					"DEPOIS", nullptr));
			else if(state == "ATUAL")
				window->pushGui(new GuiMsgBox(window, "O EMULATIONSTATION JÁ ESTÁ NA VERSÃO MAIS NOVA (" + ver + ")."));
			else
				window->pushGui(new GuiMsgBox(window, "NÃO FOI POSSÍVEL PROCURAR ATUALIZAÇÃO.\nVERIFIQUE A CONEXÃO COM A INTERNET."));
		}));
}

void GuiMenu::addVersionInfo()
{
	std::string  buildDate = (Settings::getInstance()->getBool("Debug") ? std::string( "   (" + Utils::String::toUpper(PROGRAM_BUILT_STRING) + ")") : (""));

	mVersion.setFont(Font::get(FONT_SIZE_SMALL));
	mVersion.setColor(0x5E5E5EFF);
	// BTV9: versão do release instalado (arquivo VERSION ao lado do executável)
	std::string release;
	std::ifstream vf(Utils::FileSystem::getExePath() + "/VERSION");
	if(vf && std::getline(vf, release) && !release.empty())
		mVersion.setText("EMULATIONSTATION " + Utils::String::toUpper(release) + buildDate);
	else
		mVersion.setText("EMULATIONSTATION V" + Utils::String::toUpper(PROGRAM_VERSION_STRING) + buildDate);
	mVersion.setHorizontalAlignment(ALIGN_CENTER);
	addChild(&mVersion);
}

